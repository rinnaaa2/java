    // Метод для обновления таблицы из коллекции
    private void updateTableFromList() {
        tableModel.setRowCount(0);
        for (RecIntegral rec : dataList) {
            String resultStr = rec.hasResult ? 
                String.format("%.6f", rec.result) : "";
            tableModel.addRow(new Object[]{
                rec.lowerLimit,
                rec.upperLimit,
                rec.step,
                resultStr
            });
        }
    }
    
    // Метод для обновления коллекции из таблицы
    private void updateListFromTable() {
        dataList.clear();
        for (int i = 0; i < tableModel.getRowCount(); i++) {
            try {
                double lowerLimit = Double.parseDouble(
                    tableModel.getValueAt(i, 0).toString());
                double upperLimit = Double.parseDouble(
                    tableModel.getValueAt(i, 1).toString());
                double step = Double.parseDouble(
                    tableModel.getValueAt(i, 2).toString());
                
                String resultStr = tableModel.getValueAt(i, 3).toString();
                boolean hasResult = !resultStr.trim().isEmpty();
                
                RecIntegral rec;
                if (hasResult) {
                    rec = new RecIntegral(lowerLimit, upperLimit, step, 
                        Double.parseDouble(resultStr));
                } else {
                    rec = new RecIntegral(lowerLimit, upperLimit, step);
                }
                dataList.add(rec);
            } catch (NumberFormatException | NullPointerException e) {
                // Пропускаем некорректные строки
            }
        }
    }
    
