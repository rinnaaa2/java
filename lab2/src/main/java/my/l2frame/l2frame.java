    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        // TODO add your handling code here:
        if (dataList.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this,
            "Коллекция пуста! Нечего восстанавливать.\n\n" +
            "Чтобы добавить данные в коллекцию:\n" +
            "Заполните поля и нажмите 'Внести'\n" +
            "Или рассчитайте интеграл для существующих строк",
            "Информация",
            javax.swing.JOptionPane.INFORMATION_MESSAGE);
        return;
    }
    
    // Если в таблице уже есть данные
    if (tableModel.getRowCount() > 0) {
        int confirm = javax.swing.JOptionPane.showConfirmDialog(this,
            "В таблице уже есть " + tableModel.getRowCount() + " записей!\n\n" +
            "Что вы хотите сделать?\n" +
            "'Да' - заменить текущие данные данными из коллекции\n" +
            "'Нет' - добавить данные из коллекции в конец таблицы\n" +
            "Отмена",
            "Восстановление данных",
            javax.swing.JOptionPane.YES_NO_CANCEL_OPTION);
        
        if (confirm == javax.swing.JOptionPane.CANCEL_OPTION) {
            return;
        }
        
        if (confirm == javax.swing.JOptionPane.YES_OPTION) {
            // Заменяем данные
            tableModel.setRowCount(0);
            updateTableFromList();
            javax.swing.JOptionPane.showMessageDialog(this,
                "Таблица заменена данными из коллекции!\n" +
                "Записей загружено: " + dataList.size(),
                "Успех",
                javax.swing.JOptionPane.INFORMATION_MESSAGE);
        } else {
            // Добавляем данные
            int addedCount = 0;
            for (RecIntegral rec : dataList) {
                boolean exists = false;
                for (int i = 0; i < tableModel.getRowCount(); i++) {
                    try {
                        double existingLower = Double.parseDouble(
                            tableModel.getValueAt(i, 0).toString());
                        double existingUpper = Double.parseDouble(
                            tableModel.getValueAt(i, 1).toString());
                        double existingStep = Double.parseDouble(
                            tableModel.getValueAt(i, 2).toString());
                        
                        if (existingLower == rec.lowerLimit && 
                            existingUpper == rec.upperLimit && 
                            existingStep == rec.step) {
                            exists = true;
                            break;
                        }
                    } catch (Exception e) {}
                }
                
                if (!exists) {
                    String resultStr = rec.hasResult ? 
                        String.format("%.6f", rec.result) : "";
                    tableModel.addRow(new Object[]{
                        rec.lowerLimit,
                        rec.upperLimit,
                        rec.step,
                        resultStr
                    });
                    addedCount++;
                }
            }
            
            // Синхронизируем коллекцию
            updateListFromTable();
            
            javax.swing.JOptionPane.showMessageDialog(this,
                "Добавлено новых записей: " + addedCount + "\n" +
                "Всего записей в таблице: " + tableModel.getRowCount(),
                "Успех",
                javax.swing.JOptionPane.INFORMATION_MESSAGE);
        }
    } else {
        // Таблица пуста - просто восстанавливаем
        updateTableFromList();
        javax.swing.JOptionPane.showMessageDialog(this,
            "Таблица восстановлена!\n" +
            "Записей загружено: " + dataList.size(),
            "Успех",
            javax.swing.JOptionPane.INFORMATION_MESSAGE);
        }
    }//GEN-LAST:event_jButton4ActionPerformed

