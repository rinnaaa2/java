    private double calculateIntegral(double a, double b, double h) {
    double sum = 0.0;
    double x = a;
    
    while (x < b) {
        double nextX = Math.min(x + h, b);//усечение шага
        double y1 = Math.cos(x * x);
        double y2 = Math.cos(nextX * nextX);
        sum += (y1 + y2) * (nextX - x) / 2.0;//площадь 
        x = nextX;
    }
    
    return sum;
}
